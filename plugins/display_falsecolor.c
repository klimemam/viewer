static void fill_lut(uint8_t* rgb, uint32_t entries) {
    if (entries == 256) { memcpy(rgb, VIRIDIS, sizeof VIRIDIS); return; }
    for (uint32_t i = 0; i < entries; i++) {   /* nearest resample for other sizes */
        uint32_t s = (entries > 1) ? (i * 255u) / (entries - 1u) : 0;
        memcpy(rgb + (size_t)i * 3, VIRIDIS + (size_t)s * 3, 3);
    }
}

